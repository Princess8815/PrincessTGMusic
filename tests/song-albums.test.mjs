import assert from "node:assert/strict";
import {songAlbums, earliestRelease, originalRelease, releaseForAlbums, validatedAlbums, membershipFields, renamedMembership} from "../script/song-albums.js";
const map=new Map([["a",{releaseDate:"2026-04-01"}],["b",{releaseDate:"2027-05-01"}],["c",{releaseDate:"2025-02-01"}],["single",{releaseDate:"2020-01-01"}]]);
assert.deepEqual(songAlbums({album:"A"}),["A"]);
assert.deepEqual(songAlbums({album:"A",albums:["A","B","a"]}),["A","B"]);
assert.deepEqual(songAlbums({album:"A, B"}),["A","B"]);
assert.equal(releaseForAlbums(["A","B"],"2026-01-01",map),"2026-01-01");
assert.equal(releaseForAlbums(["A","B","C"],"tbd",map),"2025-02-01");
assert.equal(releaseForAlbums(["Single","B"],"2026-03-01",map),"2026-03-01");
assert.equal(releaseForAlbums(["Single"],"tbd",map),"tbd");
assert.equal(earliestRelease("tbd","2026-02-30","2026-03-01"),"2026-03-01");
assert.equal(originalRelease({releaseDate:"2026-01-01"}),"2026-01-01");
assert.equal(originalRelease({originalReleaseDate:"tbd",releaseDate:"2026-01-01"}),"tbd");
assert.throws(()=>validatedAlbums(["A","a"],["A","a"]));
assert.throws(()=>validatedAlbums(["","B"],["A","B"]));
assert.throws(()=>validatedAlbums(["A","B","C","D"],["A","B","C","D"]));
assert.deepEqual(membershipFields(["A","B"]),{album:"A",albums:["A","B"]});
assert.deepEqual(renamedMembership({album:"A",albums:["A","B","C"]},"B","D"),["A","D","C"]);
assert.deepEqual(renamedMembership({album:"A",albums:["A","B","C"]},"A","D"),["D","B","C"]);
console.log("16 membership and earliest-release assertions passed");
