const assert=require("node:assert/strict");
const fs=require("node:fs");
const os=require("node:os");
const path=require("node:path");
const {legacyTarget,updateMetadata,legacyPage,build,DEST,OLD}=require("../build-site.cjs");
const redirect=url=>legacyTarget(new URL(url));
assert.equal(DEST,"https://princesstg-creations.com");
assert.equal(redirect(OLD),DEST+"/");
assert.equal(redirect(OLD+"/"),DEST+"/");
assert.equal(redirect(OLD+"/pages/store.html"),DEST+"/pages/store.html");
assert.equal(redirect(OLD+"/audioPlayer/pages/song.html?id=dying-star#lyrics"),DEST+"/audioPlayer/pages/song.html?id=dying-star#lyrics");
assert.equal(redirect(OLD+"/pages/docs-board.html?share=abc%26def#doc-heading-intro"),DEST+"/pages/docs-board.html?share=abc%26def#doc-heading-intro");
assert.equal(redirect(OLD+"/images/logo%20avatar.png"),DEST+"/images/logo%20avatar.png");
assert.equal(redirect(OLD+"//evil.example/"),DEST+"//evil.example/");
assert.equal(redirect("https://princess8815.github.io/PrincessTGMusic-other"),null);
assert.equal(redirect("https://princess8815.github.io/poetry/"),null);
assert.equal(redirect(DEST+"/pages/store.html"),null);
assert.equal(redirect("http://localhost:5501/index.html"),null);
const original='<html><head><title>My Song</title><meta property="og:title" content="My Song"><meta property="og:image" content="'+OLD+'/images/a.png"><meta property="og:url" content="'+OLD+'/audioPlayer/pages/my-song.html"><meta name="twitter:description" content="My description"><script src="checkout.js"></script></head><body>original '+OLD+'</body></html>';
const normal=updateMetadata(original);
assert.ok(normal.includes(DEST+"/images/a.png"));
assert.ok(normal.includes(DEST+"/audioPlayer/pages/my-song.html"));
assert.ok(normal.includes("original "+OLD));
assert.ok(normal.includes("checkout.js"));
const oldPages="https://princesstgcreations.pages.dev";
const migrated=updateMetadata(`<meta property="og:url" content="${oldPages}/pages/store.html"><meta name="twitter:image" content="${oldPages}/images/logo%20avatar.png"><link rel="canonical" href="${OLD}/pages/store.html"><meta property="og:image:secure_url" content="${OLD}/images/a.png"><meta property="og:url" content="${oldPages}.evil.example/a"><a href="${oldPages}/">original link</a><meta property="og:description" content="${oldPages}/ original text">`);
assert.ok(migrated.includes('content="'+DEST+'/pages/store.html"'));
assert.ok(migrated.includes('content="'+DEST+'/images/logo%20avatar.png"'));
assert.ok(migrated.includes('href="'+DEST+'/pages/store.html"'));
assert.ok(migrated.includes('content="'+DEST+'/images/a.png"'));
assert.ok(migrated.includes(oldPages+".evil.example/a"));
assert.ok(migrated.includes('href="'+oldPages+'/"'));
assert.ok(migrated.includes('content="'+oldPages+'/ original text"'));
assert.equal(updateMetadata(migrated),migrated);
const moved=legacyPage(original,"audioPlayer/pages/my-song.html");
assert.ok(moved.includes("My Song"));
assert.ok(moved.includes("My description"));
assert.ok(moved.includes(DEST+"/images/a.png"));
assert.ok(moved.includes("location.replace(target)"));
assert.ok(!moved.includes("checkout.js"));
assert.ok(!moved.includes("original "+OLD));
assert.ok(moved.includes('href="'+DEST+'/audioPlayer/pages/my-song.html"'));
assert.ok(legacyPage(original,"404.html").includes('href="'+DEST+'/"'));
const root=fs.mkdtempSync(path.join(os.tmpdir(),"ptg-migration-"));
try {
 for(const dir of ["albums","arts","audioPlayer","data","images","pages","script","styles"])fs.mkdirSync(path.join(root,dir));
 for(const file of ["index.html","404.html","pages/store.html"])fs.writeFileSync(path.join(root,file),original);
 const ads = "google.com, pub-1234567890123456, DIRECT, f08c47fec0942fa0\n";
 fs.writeFileSync(path.join(root,"ads.txt"),ads);
 fs.writeFileSync(path.join(root,"images","asset.png"),"asset");
 fs.writeFileSync(path.join(root,"script","unused.bak"),"backup");
 fs.mkdirSync(path.join(root,"workers"));fs.writeFileSync(path.join(root,"workers","private.js"),"private");
 assert.equal(build("legacy",root),3);
 assert.equal(fs.readFileSync(path.join(root,"dist/ads.txt"),"utf8"),ads);
 assert.ok(fs.readFileSync(path.join(root,"dist/pages/store.html"),"utf8").includes("location.replace"));
 assert.equal(fs.readFileSync(path.join(root,"dist/images/asset.png"),"utf8"),"asset");
 assert.ok(!fs.existsSync(path.join(root,"dist/script/unused.bak")));
 assert.ok(!fs.existsSync(path.join(root,"dist/workers")));
 assert.equal(build("cloudflare",root),3);
 assert.equal(fs.readFileSync(path.join(root,"dist/ads.txt"),"utf8"),ads);
 assert.ok(fs.readFileSync(path.join(root,"dist/pages/store.html"),"utf8").includes("checkout.js"));
 assert.equal(fs.readFileSync(path.join(root,"pages/store.html"),"utf8"),original);
}finally{fs.rmSync(root,{recursive:true,force:true});}
console.log("Site migration assertions passed");
