import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
const source=await readFile(new URL("../rewards.js",import.meta.url),"utf8");
const {adminSandboxRewards,rewardProject,rewardAvailable,eligibleStaffAccount}=await import("data:text/javascript;base64,"+Buffer.from(source).toString("base64"));
const test={STORE_MODE:"test",FIREBASE_PROJECT:"prod",REWARD_FIREBASE_PROJECT:"prod",FIREBASE_REWARD_SERVICE_ACCOUNT:"mock",ADMIN_TEST_TIDE:"yes"};
const account=(role,status="active")=>({fields:{role:{stringValue:role},status:{stringValue:status}}});
assert.equal(adminSandboxRewards(test),true);
assert.equal(rewardProject(test),"prod");
assert.equal(rewardAvailable(test,{reward_uid:"staff"}),true);
assert.equal(rewardAvailable(test,{}),false);
assert.equal(rewardProject({...test,ADMIN_TEST_TIDE:"no"}),"");
assert.equal(rewardProject({...test,FIREBASE_REWARD_SERVICE_ACCOUNT:""}),"");
assert.equal(rewardProject({...test,REWARD_FIREBASE_PROJECT:""}),"");
assert.equal(adminSandboxRewards({...test,STORE_MODE:"live"}),false);
assert.equal(rewardProject({...test,STORE_MODE:"live"}),"prod");
assert.equal(rewardAvailable({...test,STORE_MODE:"live"},{}),true);
assert.equal(rewardProject({...test,REWARD_FIREBASE_PROJECT:"isolated"}),"isolated");
assert.equal(adminSandboxRewards({...test,REWARD_FIREBASE_PROJECT:"isolated"}),false);
assert.equal(eligibleStaffAccount(account("admin")),true);
assert.equal(eligibleStaffAccount(account("owner")),true);
assert.equal(eligibleStaffAccount(account("user")),false);
assert.equal(eligibleStaffAccount(account("admin","banned")),false);
assert.equal(eligibleStaffAccount(account("owner","archived")),false);
assert.equal(eligibleStaffAccount({}),false);
console.log("18 admin sandbox reward policy assertions passed");
