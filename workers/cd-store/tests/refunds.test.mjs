import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
const source=await readFile(new URL("../refunds.js",import.meta.url),"utf8");
const {refundSummary,taxAction,refundEvents}=await import("data:text/javascript;base64,"+Buffer.from(source).toString("base64"));
const item=(id,amount,status="succeeded",extra={})=>({id:"re_"+id,amount,status,currency:"usd",payment_intent:"pi_order",...extra});
const summarize=(list)=>refundSummary(list,"pi_order",1055);
assert.deepEqual(summarize([]),{refunded:0,pending:0,status:"paid"});
assert.equal(summarize([item("1",1055)]).status,"refunded");
assert.equal(summarize([item("1",500)]).status,"partially_refunded");
assert.equal(summarize([item("1",1055,"pending")]).status,"refund_pending");
assert.equal(summarize([item("1",1055,"requires_action")]).pending,1055);
assert.equal(summarize([item("1",1055,"failed")]).status,"paid");
assert.equal(summarize([item("1",1055,"canceled")]).refunded,0);
assert.equal(summarize([item("1",500),item("2",555)]).status,"refunded");
assert.throws(()=>summarize([item("1",1056)]));
assert.throws(()=>summarize([item("1",500),item("1",500)]));
assert.throws(()=>summarize([item("1",500,"succeeded",{currency:"eur"})]));
assert.throws(()=>summarize([item("1",500,"succeeded",{payment_intent:"pi_other"})]));
assert.throws(()=>summarize([item("1",500,"unknown")]));
assert.equal(taxAction({},summarize([item("1",1055)]),1055),"full_pending");
assert.equal(taxAction({},summarize([item("1",500)]),1055),"manual_review");
assert.equal(taxAction({tax_state:"manual_review"},summarize([item("1",1055)]),1055),"manual_review");
assert.equal(taxAction({tax_reversal:"tax_1",tax_state:"reversed"},summarize([item("1",1055)]),1055),"reversed");
assert.equal(taxAction({},summarize([item("1",1055,"pending")]),1055),"none");
assert.ok(refundEvents.has("refund.created")&&refundEvents.has("refund.updated")&&refundEvents.has("refund.failed")&&refundEvents.has("charge.refunded"));
console.log("19 refund helper assertions passed");
